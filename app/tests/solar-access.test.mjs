import assert from 'node:assert/strict';
import {volume,rayHit,orientation,facets,candidateLoss,evaluate} from '../public/solar-access.js';
import {rotateEdge,sunSamples} from '../public/daylight-facades.js';
const slab=volume([[-10,-10],[10,-10],[10,10],[-10,10]],12,1,{holes:[[[-2,-2],[2,-2],[2,2],[-2,2]]]});
assert.equal(rayHit([0,0,0],[0,0,1],slab),null,'A slab opening must transmit the ray');
assert.equal(rayHit([5,0,0],[0,0,1],slab),12,'A solid slab must block the ray');
const mass=volume([[10,-2],[20,-2],[20,2],[10,2]],0,30,{owner:'neighbor',kind:'mass'});
assert.equal(rayHit([0,0,5],[1,0,.1],mass),10);
assert.equal(rayHit([0,0,40],[1,0,.1],mass),null,'A ray above a stepped roof must remain clear');
assert.equal(orientation([0,1],0).ns,1);
assert.equal(orientation([1,0],0).ns,0);
assert.ok(orientation([1,0],90).ns>.999);
const f=rotateEdge([0,0],[0,28],10),fs=facets(f,0);
assert.ok(fs.some(x=>x.name!=='main'&&x.glazed&&x.ns>.9),'East/west wings need north/south glazed returns');
const scene=[volume([[-20,0],[0,0],[0,28],[-20,28]],0,36,{owner:'unit',kind:'mass'})];
assert.ok(candidateLoss(f,{id:'unit'},scene,[{owner:'other',o:[3,2,6],dir:[-1,0,.1]}])>0,'New neighbor obstruction must reject a candidate');
const score=evaluate(f,6,'unit',[],sunSamples(40.7,0),0,true);
assert.ok(Number.isFinite(score.score));assert.ok(score.rays.length>0);
console.log('PASS solar geometry, slab openings, stepped obstruction, orientation, glazed returns and neighbor protection');
